public class Calculator {
	
	public int sum(int a,int b)
	{
		return a+b;
	}
	
	public int subtract(int a,int b) {
		return a-b;
	}
	
	public int mul(int a,int b) {
		return a*b;
	}
	
	public int div(int a,int b) {
		return a/b;
	}

}
